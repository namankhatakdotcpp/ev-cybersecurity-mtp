"""Gate 7: generate the final results report from the experiment registry (Protocol v1 sections 12 and 13).

Every number in the generated file is read from results/registry.csv and the per-run summary.json files; the only
static text is wording (scope, limitations, the claims register), which contains no result numbers.

  python -m backend.pipeline.gate7.build_final_report      ->  docs/report/FINAL_REPORT.md
"""
import json
import re

import pandas as pd

from ..gate2.benchmark import load_gate3
from ..gate2.config import REPO_ROOT

SETS = ["B0", "B", "G", "BG"]
LEARNERS = [("ridge", "Ridge (offset)"), ("rf", "Random forest"), ("hgb", "Boosting")]
SIMPLE_SET = {"B0": 0, "B": 1, "G": 2, "BG": 3}
SIMPLE_LEARNER = {"ridge": 0, "hgb": 1, "rf": 2}
SLMS = ["mistral:7b-instruct", "llama3.1:8b", "phi3:3.8b", "gemma2:9b", "qwen2.5:7b"]


class Reg:
    def __init__(self, cfg):
        self.results = cfg["paths_resolved"]["results_dir"]
        self.reg = pd.read_csv(self.results / "registry.csv", dtype=str)

    def latest(self, name):
        rows = self.reg[self.reg["experiment_id"].str.match(rf"^{re.escape(name)}_\d{{8}}_")]
        if rows.empty:
            raise KeyError(name)
        e = rows.sort_values("timestamp").iloc[-1]
        return json.loads((self.results / e["experiment_id"] / "summary.json").read_text(encoding="utf-8")), e["experiment_id"]


def f(x, k=3):
    return f"{x:.{k}f}"


def ci(pt, c, k=3):
    return f"{pt:.{k}f} [{c[0]:.{k}f}, {c[1]:.{k}f}]"


def pp(d, k=3):
    return f"{d['p']:.{k}f} [{d['lo']:.{k}f}, {d['hi']:.{k}f}]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def build():
    cfg = load_gate3()
    R = Reg(cfg)
    md = []
    runs = {}

    def get(name):
        s, eid = R.latest(name)
        runs[name] = eid
        return s["metrics"] if "metrics" in s else s

    a, b = get("h1_claim_a"), get("h1_claim_b")
    g3 = {k: get(f"g3_grid_{k}") for k, _ in LEARNERS}
    s1, s2, s8 = get("g3_secondary_S1"), get("g3_secondary_S2"), get("g3_exploratory_S8")
    sel = get("g4_selection_bias")
    s6 = get("g4_s6_ridge")
    s5, grid, det = get("g6_s5_skip_vs_charge"), get("g6_ridge_grid_sensitivity"), get("g6_eeg_detrended")
    pri = a["primary"]

    md += ["# Final results report (generated)", "",
           "Generated by `backend/pipeline/gate7/build_final_report.py` from `results/registry.csv` and the run folders; do not edit by hand. "
           "No result number below is typed in. Scope, wording rules and limitations are static text. Everything is associational and mostly exploratory; "
           "the protocol was frozen before the analyses (tag `protocol-v1`) but the target was redefined after the data had been seen (Gate 0), "
           "and no untouched test set exists.", "",
           "Registry runs used: " + "; ".join(f"`{v}`" for v in runs.values()), ""]

    # ---- 1 data
    md += ["## 1. Data", "",
           f"- Primary set (T1: charge decisions at stations with at least one attacked and one safe available kiosk): {pri['n_rows']} rows, {pri['n_participants']} participants, {pri['n_events']} events.",
           f"- EEG-matched set: {s6['n_rows']} rows, {s6['n_participants']} participants, {s6['n_events']} events.",
           f"- EEG coverage: {100 * sel['coverage']['share_after_eeg_end']:.1f}% of decision windows of participants with a confirmed recording fall after the recording ended; "
           f"median trial index {sel['coverage']['median_trial_usable']:.0f} for rows with usable EEG versus {sel['coverage']['median_trial_after_end']:.0f} for rows after the end.", ""]

    # ---- 2 H1
    pa, bm = pri, b
    d = bm["delta_auroc"]["BG_minus_B"]
    md += ["## 2. Primary hypothesis H1 (Gate 2)", "",
           f"- Claim A (gaze block beyond exposure, design and behaviour): LRT chi-square {pa['lrt']['stat']:.2f}, df {pa['lrt']['df']:.0f}, p = {pa['lrt']['p']:.3f}; "
           f"participant-block permutation p = {a['permutation_lrt']['p']:.3f}.",
           f"- Claim B (out-of-sample): AUROC difference BG minus B = {d['point']:+.3f} [{d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}]; permuted-gaze control p = {bm['permutation']['p_auc_BG_ge_obs']:.3f}.",
           "- By the rule fixed in Protocol section 2: H1 is not supported unless both claims hold. They do not.", ""]

    # ---- 3 ML grid
    md += ["## 3. ML benchmark (Gate 3), mean out-of-fold AUROC [95% participant-bootstrap CI]", ""]
    rows = []
    cand = []
    for k, name in LEARNERS:
        m = g3[k]
        for s in SETS:
            pt, c = m["point"][s], m["ci"][s]["auroc"]
            rows.append([name, s, ci(pt["auroc"], c), f(pt["brier"]), f(pt["calib_slope"], 2), f(pt["false_safe_B"], 2), f(pt["false_warning_B"], 2)])
            cand.append(dict(learner=k, set=s, auroc=pt["auroc"], ci=c, slope=pt["calib_slope"], fsB=pt["false_safe_B"], fwB=pt["false_warning_B"], brier=pt["brier"]))
    md += table(["Learner", "Set", "AUROC [CI]", "Brier", "Calib. slope", "False-safe at recall 0.80 point", "False-warning at that point"], rows)
    md += ["", "Paired AUROC differences to B0 (participant bootstrap):", ""]
    pr = []
    for k, name in LEARNERS:
        for key, lab in (("B_minus_B0", "B - B0"), ("G_minus_B0", "G - B0"), ("BG_minus_B0", "BG - B0")):
            x = g3[k]["paired"][key]["auroc"]
            pr.append([name, lab, f"{x['mean']:+.3f} [{x['ci'][0]:+.3f}, {x['ci'][1]:+.3f}]"])
    md += table(["Learner", "Contrast", "Difference [CI]"], pr)
    md += ["", f"- S1 (gaze alone vs exposure): LRT p = {s1['lrt']['p']:.3f}, AUROC difference {s1['delta_auroc']['mean']:+.3f} [{s1['delta_auroc']['ci'][0]:+.3f}, {s1['delta_auroc']['ci'][1]:+.3f}], permutation p = {s1['permutation']['p']:.3f}.",
           f"- S2 (first {s2['early_window_s']:.0f} s only): LRT p = {s2['lrt']['p']:.3f}, AUROC difference {s2['delta_auroc_BGE_minus_BE']['mean']:+.3f} [{s2['delta_auroc_BGE_minus_BE']['ci'][0]:+.3f}, {s2['delta_auroc_BGE_minus_BE']['ci'][1]:+.3f}], permutation p = {s2['permutation']['p']:.3f}.",
           f"- Any pre-specified model beats B0 with a CI above zero: {'yes' if s8['any_prespecified_model_beats_B0_with_ci_above_zero'] else 'no'}.", ""]

    # ---- 4 EEG
    pe = s6["point"]
    md += ["## 4. EEG on the matched set (Gate 4, exploratory)", "",
           *table(["Set", "AUROC [CI]"], [[s, ci(pe[s]["auroc"], s6["ci"][s]["auroc"])] for s in ("B0", "B", "BG", "BGE") if s in pe]), ""]
    pk = [k for k in s6["paired"] if "BGE" in k and "BG" in k]
    for k in pk:
        x = s6["paired"][k]["auroc"]
        tag = "primary contrast" if k == "BGE_minus_BG" else "exploratory, not designated primary, not corrected for multiple comparisons"
        md.append(f"- {k.replace('_minus_', ' minus ')} ({tag}): {x['mean']:+.3f} [{x['ci'][0]:+.3f}, {x['ci'][1]:+.3f}]")
    md += [f"- Detrended on trial index (Gate 6): BGE detrended minus BG {det['primary_BGE_detrended_minus_BG']['auroc']['mean']:+.3f} [{det['primary_BGE_detrended_minus_BG']['auroc']['ci'][0]:+.3f}, {det['primary_BGE_detrended_minus_BG']['auroc']['ci'][1]:+.3f}], permutation p = {det['permutation_BGE_detrended']['p']:.3f}.", ""]

    # ---- 5 exploratory
    mi = s5["results"]["main_informative"]
    md += ["## 5. Exploratory follow-ups (Gate 6)", "",
           f"- Extended ridge grid: B0 {f(grid['auroc']['B0']['point'])}, B {f(grid['auroc']['B']['point'])}, BG {f(grid['auroc']['BG']['point'])}; BG minus B {grid['delta_auroc']['mean']:+.4f} [{grid['delta_auroc']['ci'][0]:+.4f}, {grid['delta_auroc']['ci'][1]:+.4f}].",
           f"- S5, skip vs charge on mixed stations ({mi['n_rows']} rows, {mi['n_events']} skips): skip rate {100 * mi['skip_rate']:.1f}%; LRT p = {mi['lrt']['p']:.4f}; Holm upper bounds S5 {s5['holm']['S5']['holm_adjusted_upper_bound']:.3f}, S6 {s5['holm']['S6']['holm_adjusted_upper_bound']:.3f}, S1 {s5['holm']['S1']['holm_adjusted_upper_bound']:.3f}, S2 {s5['holm']['S2']['holm_adjusted_upper_bound']:.3f}. See the Gate 6 report for why this is not a gaze result.", ""]

    # ---- 6 SLM
    M = {}
    for m in SLMS:
        M[m] = get("g5_slm_" + m.replace(":", "_"))
    md += ["## 6. Language models (Gate 5; separate track, never pooled with the ML results)", ""]
    for key, label in (("V1|all", "V1 cue-free"), ("V2|excl_label", "V2 image descriptions, label-flagged kiosks excluded (pre-committed headline)")):
        rows = []
        for m in SLMS:
            d_ = M[m]["detection"][key]
            rows.append([m, pp(d_["false_safe"], 2), pp(d_["false_warning"], 2), f(d_["balanced_accuracy"]),
                         f"{d_['best_reference']} {f(d_['best_reference_balanced_accuracy'])}",
                         "yes" if d_["degenerate"]["flag"] else "no", pp(d_["failed_replies"], 2)])
        md += [f"**Detection, {label}**", "", *table(["Model", "False-safe", "False-warning", "Balanced acc.", "Best reference (bal. acc.)", "Degenerate", "Failed replies"], rows), ""]
    rows = []
    for m in SLMS:
        for key in ("V1|all", "V2|excl_label"):
            r_ = M[m]["recommendation"][key]
            mx = r_["mixed"]
            rows.append([m, key.split("|")[0], pp(mx["safe"], 2), pp(mx["attacked"], 2), pp(mx["skip"], 2), f(mx["random_choice_safe_rate"]), pp(r_["all_attacked"]["attacked"], 2)])
    md += ["**Recommendation on mixed stations (all-attacked column: attacked kiosk chosen)**", "", *table(["Model", "Variant", "Safe kiosk chosen", "Attacked kiosk chosen", "SKIP", "Random-choice safe rate", "All-attacked: attacked chosen"], rows), ""]
    rows = []
    for m in SLMS:
        for v in ("V1", "V2"):
            c_ = M[m]["consistency"].get(v)
            if not c_ or not c_["detection_per_seed"]:
                continue
            fs = [x["false_safe"] for x in c_["detection_per_seed"]]
            rows.append([m, v, len(fs), f"{sum(fs) / len(fs):.3f} [{min(fs):.3f}, {max(fs):.3f}]", f"{sum(x['degenerate'] for x in c_['detection_per_seed'])}/{len(fs)}",
                         f"{c_['agreement']['detection']['mean_pairwise_agreement']:.3f}"])
    md += ["**Consistency, 5 seeds at temperature 0.3**", "", *table(["Model", "Variant", "Seeds", "False-safe mean [min, max]", "Degenerate seeds", "Mean pairwise agreement"], rows), ""]
    md += ["The malicious-override pass was run (600 replies) but is **not scored**; no claim about steering or compliance is made.", ""]

    # ---- 7 rubric
    md += ["## 7. Final selection rubric (Protocol v1 section 12; applied mechanically)", ""]
    best = max(cand, key=lambda x: x["auroc"])
    tied = [x for x in cand if x["ci"][1] >= best["ci"][0] and x["ci"][0] <= best["ci"][1]]
    simple = min(tied, key=lambda x: (SIMPLE_SET[x["set"]], SIMPLE_LEARNER[x["learner"]]))
    name = dict(LEARNERS)
    md += [f"1. **Best predictive model.** Highest mean AUROC: {name[best['learner']]}, set {best['set']}, {ci(best['auroc'], best['ci'])}. {len(tied)} of {len(cand)} model-set pairs have a CI overlapping it, so the tie rule "
           f"(simpler model wins; fewer feature blocks first, then ridge before boosting before forest) selects **{name[simple['learner']]}, set {simple['set']}**, AUROC {ci(simple['auroc'], simple['ci'])}. "
           "That model is the exposure-only baseline: it contains no gaze, behaviour or EEG feature.", ""]
    ok = [x for x in cand if 0.7 <= x["slope"] <= 1.3]
    safe = sorted(ok, key=lambda x: (x["fsB"], x["fwB"]))[0]
    close = [x for x in ok if x["fsB"] - safe["fsB"] <= 0.01]
    md += [f"2. **Best safety-oriented model.** Among {len(ok)} model-set pairs with calibration slope in [0.7, 1.3], the lowest false-safe rate at the recall-0.80 operating point is {name[safe['learner']]}, set {safe['set']}: "
           f"false-safe {f(safe['fsB'], 2)}, false-warning {f(safe['fwB'], 2)}, calibration slope {f(safe['slope'], 2)}. "
           f"{len(close)} eligible pairs are within 0.01 of that false-safe value, so the choice is the nominal minimum, not a separated winner. "
           f"False-safe is near 1 minus the 0.80 target for every model by construction; the false-warning rate ({f(min(x['fwB'] for x in ok), 2)} to {f(max(x['fwB'] for x in ok), 2)} across eligible models) is the cost, and no operating point is validated.", ""]
    se = (best["ci"][1] - best["ci"][0]) / 3.92
    near = [x for x in ok if best["auroc"] - x["auroc"] <= se]
    dep = min(near, key=lambda x: (SIMPLE_SET[x["set"]], SIMPLE_LEARNER[x["learner"]]))
    md += [f"3. **Best deployment model.** Simplest model within one standard error ({f(se)}) of the best AUROC with acceptable calibration: {name[dep['learner']]}, set {dep['set']}. "
           f"S2 does not support restricting to early-window features (LRT p = {s2['lrt']['p']:.3f}), so no keypad-stage restriction is established. "
           "Latency was not measured for the ML models. Because this model is the exposure baseline, deploying it would mean computing the share of attacked kiosks, not running a learned detector; "
           "no warning performance has been shown online.", ""]
    # SLM selection: headline V2*, exclude degenerate and models with no valid replies, lowest false-safe then failures
    key = "V2|excl_label"
    el = [m for m in SLMS if not M[m]["detection"][key]["degenerate"]["flag"]]
    el.sort(key=lambda m: (M[m]["detection"][key]["false_safe"]["p"], -(1 - M[m]["detection"][key]["false_warning"]["p"])))
    sl = el[0]
    ds = M[sl]["detection"][key]
    md += [f"4. **Best SLM (rule: lowest false-safe rate first, on the pre-committed V2 headline; degenerate models excluded).** {sl}: false-safe {pp(ds['false_safe'], 2)}, false-warning {pp(ds['false_warning'], 2)}, "
           f"balanced accuracy {f(ds['balanced_accuracy'])} against the best reference {ds['best_reference']} at {f(ds['best_reference_balanced_accuracy'])}. "
           "The selection is the least-bad under the rule, not a good detector: no model beats the best reference, and low false-safe here comes with a high false-warning rate "
           "(models warn on almost any kiosk with an image description). Latency and memory are in the Gate 5 master table.", ""]
    k1 = "V1|all"
    el1 = sorted([m for m in SLMS if not M[m]["detection"][k1]["degenerate"]["flag"]], key=lambda m: M[m]["detection"][k1]["false_safe"]["p"])
    md += [f"   Same rule on V1 (cue-free), for transparency: {el1[0]} has the lowest false-safe among non-degenerate models ({pp(M[el1[0]]['detection'][k1]['false_safe'], 2)}, false-warning {pp(M[el1[0]]['detection'][k1]['false_warning'], 2)}); "
           "the choice of variant changes the selected model, which is why no ranking of models is claimed.", "",
           "**Best overall system: withheld** (no human validation; Protocol section 12).", ""]

    # ---- 8 limitations & claims
    md += ["## 8. Limitations", "",
           "- Sample size and no untouched test set: earlier decisions (D045 to D063) iterated on the same participants; every result here is pre-specified-but-exploratory.",
           "- The target was redefined after Gate 0 showed the old one was dominated by randomised kiosk layout.",
           "- EEG rows are a biased subset (earlier stations, April-heavy), preprocessing is minimal, and power is limited; 'not detected' is not 'no effect'.",
           "- The window ends at the decision event, so duration and gaze counts are mechanically linked to skip versus charge.",
           "- The assistant's replies and the benign or malicious condition were not logged, so their effect cannot be assessed.",
           "- Several ridge and boosting grids selected their weakest setting; a wider ridge grid gave the same conclusion.",
           "- SLM scenario set: quota-sampled, text-only, one main decoding setting, image descriptions produced by another model; detection is not blind to the investigators.",
           "- A provisional scoring look preceded the Gate 5 scoring spec (D078); one mistral consistency item is missing and its file contains duplicates (D080).",
           "- Many strata and sensitivity runs; unadjusted p-values are descriptive.", "",
           "## 9. Claims register", "",
           *table(["Claim", "Status"], [
               ["Gaze adds to behaviour for the redefined target (H1)", "Not supported"],
               ["Any pre-specified ML model beats exposure-only B0", "No"],
               ["EEG adds information", "Not established (biased subset, low power)"],
               ["Skipping follows exposure", "Not supported"],
               ["Any tested SLM detects attacked kiosks better than simple rules", "No"],
               ["Any tested SLM recommends a safe kiosk above chance", "No"],
               ["An SLM can be steered by a malicious instruction", "Not assessed (pass run, not scored)"],
               ["A warning operating point is validated", "No"],
               ["A best overall system", "Withheld"]]), "",
           "## 10. Out of scope and future work", "",
           "The human experiment on automation bias needs new data (three randomised assistant conditions, assistant replies and condition logged, decision latency and pre-decision gaze logged, full-session EEG, a pre-registered scenario set and primary outcome). "
           "Video-based AOI analysis is closed for the existing data (D060 to D062).", ""]

    out = REPO_ROOT / "docs" / "report" / "FINAL_REPORT.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    build()
